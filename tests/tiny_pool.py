def build(db_path: Path) -> Path:
    """Create a card pool at `db_path`. Returns it, so callers can chain.

    Built once per process and copied thereafter -- see `_CACHE_DIR`. Before
    the cache, the ~75 tests taking a `pool` fixture each paid the ingest
    themselves, which was about two of the suite's six minutes.
    """
    global _CACHE_DIR
    if _CACHE_DIR is None:
        _CACHE_DIR = tempfile.TemporaryDirectory(prefix="tiny-pool-")
        _build_into(Path(_CACHE_DIR.name) / "tiny.duckdb")
    db_path = Path(db_path)
    db_path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(Path(_CACHE_DIR.name) / "tiny.duckdb", db_path)
    return db_path


def _build_into(db_path: Path) -> None:
    from mtglab.cards.db import connect, load_oracle, load_printings

    jsonl = Path(db_path).parent / "tiny-oracle.jsonl"
    jsonl.parent.mkdir(parents=True, exist_ok=True)
    jsonl.write_text("\n".join(json.dumps(c) for c in CARDS), encoding="utf-8")

    printings = Path(db_path).parent / "tiny-printings.jsonl"
    printings.write_text("\n".join(json.dumps(p) for p in PRINTINGS),
                         encoding="utf-8")

    con = connect(db_path)
    try:
        load_oracle(con, jsonl)
        load_printings(con, printings)
    finally:
        con.close()


# --------------------------------------------------------------- a real deck
#
# The API's card-fact tests used to run against `decks/goreclaw-stompy`, which
# meant they needed the whole 35,000-card pool to say anything -- and so they
# skipped everywhere except the maintainer's laptop. This deck is built
# entirely out of the cards above, so the same assertions run against a card pool
# CI can construct in about a second.
#
# It is deliberately *shaped* like Goreclaw's real list rather than being it:
# a mono-green commander, a legal 99, and exactly one banned card. What it is
# not is a plausible deck -- 92 Forests is not a mana base, it is the cheapest
# legal way to reach 99 cards without inventing ninety more fixture rows.
# Nothing here should be read as deckbuilding advice, and nothing in `decks/`
# depends on it.

#: The non-basic slots. Basics fill the rest.
#:
#: Deliberately short. `suggest.replacements_for` excludes everything already
#: in the list, so a fixture that ran every green creature in `CARDS` would
#: shortlist nothing and `assert target["candidates"]` would be asserting the
#: absence of a bug it could no longer see. Craterhoof Behemoth, Terastodon
#: and Woodfall Primus are held *out* of the deck on purpose, so they are
#: available as candidates for the Titan's slot.
_SPELLS = [
    ("Sol Ring", "ramp", "Two mana on turn one, and it always has been."),
    ("Regal Behemoth", "threat", "Doubles the mana and refills the hand."),
    ("Vorinclex, Voice of Hunger", "threat", "Taxes every opponent's mana."),
]

#: Swapped in for the banned Titan when a clean deck is what's wanted.
_LEGAL_SEVEN_DROP = (
    "Cultivator Colossus", "threat",
    "Trample body that puts lands onto the battlefield; ramp and threat in one.",
)

#: The one illegal card, so the gate has exactly one thing to say.
_BANNED = ("Primeval Titan", "threat", "Banned in Commander -- deliberately.")


def mono_green_deck(*, clean: bool = False, stage: str = "curated"):
    """A 99-card mono-green deck built only from `CARDS`.

    With `clean=False` (the default) it runs Primeval Titan and fails the gate
    on exactly that one card, which is what makes "the gate found something"
    and "a suggestion was offered" testable. With `clean=True` the Titan's slot
    is a legal seven-drop instead and the deck passes, which is what makes
    "a clean deck has nothing to suggest" testable without a second fixture.

    Returned fresh each call: `MemoryDeckSource` mutates what it is given, and
    a shared instance would leak one test's edits into the next.
    """
    from mtglab.decks.model import CardEntry, Deck

    spells = [*_SPELLS, _LEGAL_SEVEN_DROP if clean else _BANNED]
    cards = [CardEntry(name=n, category=c, why=w) for n, c, w in spells]
    cards.append(CardEntry(
        name="Forest", category="land", qty=99 - len(spells),
        why="Basic, untapped, and the only green source this list needs."))
    assert sum(c.qty for c in cards) == 99, "the fixture deck is not 99 cards"

    return Deck(
        slug="mono-green",
        name="Mono-Green Fixture",
        status="theoretical",
        stage=stage,
        commander=["Goreclaw, Terror of Qal Sisma"],
        bracket=2,
        strategy="A fixture, not a deck. See tests/tiny_pool.py.",
        cards=cards,
    )


