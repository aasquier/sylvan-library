"""A small DuckDB pool, for the tests that cannot run without one.

Most of this project's tests deliberately need no database -- the mana solver,
the gate and the simulator all take plain records, which is what keeps them
fast and what ADR 2 was protecting. Two things are the exception, and they are
the reason this file grew:

* **Import** refuses to run without the pool, because that is *the* rule it
  enforces (rule 1, never evaluate a card from memory), so testing it against
  a fake would test the wrong thing.
* **The API's card-fact endpoints** -- swap, add, suggestions, card search --
  look every name up. Until this fixture existed they were gated on the real
  `data/mtg.duckdb`, which meant they ran on the maintainer's laptop and
  skipped in CI: 29 tests and five points of coverage that no pull request
  ever exercised.

**Every value here was read out of the real pool, never typed from memory.**
Rule 1 applies to test data too -- a fixture that names a real card and then
lies about it teaches the wrong thing, and would hide exactly the class of bug
this project has already been bitten by twice. The rows were generated by
querying `oracle_cards` and are pasted verbatim, with two deliberate trims.
`legalities` carries only the `commander` key, because that is the only one any
code path reads (`json_extract_string(legalities, 'commander')` in `db.search`,
and `CardRecord.legal_commander`). Carrying the other twenty formats would
quadruple the file to say nothing. And `PRINTINGS` carries each printing's
`artist` but not its `flavor_text`: the painter is what `pool_is_stale` asks
about, so a fixture without one reports itself as an old pool, while the
flavour text is prose nothing here reads.

**This is not a card pool redistribution.** Twenty-one cards chosen to exercise
resolution rules is a test fixture; ADR 6 and rule 5 are about the bulk data,
which stays out of git and off the image. If this file ever needs to grow to
the size where that distinction gets uncomfortable, that is the signal to make
CI build a card pool rather than commit one.

What each card is here for:

* **Gyome, Master Chef** -- a legendary commander, and the B/G identity the
  import tests resolve against.
* **Sol Ring** -- a colourless artifact every deck can legally run.
* **Swamp** / **Forest** -- basics, exempt from the singleton rule, so a
  fixture deck can reach 99 cards without inventing 90 distinct ones.
* **Primeval Titan** -- banned in Commander, so the gate has something real to
  catch on day one.
* **Emrakul, the Aeons Torn** -- also banned, and the second half of the pair
  the pool tools exist for: `search_cards` filters to Commander-legal, so
  both of the cards the real library deliberately fails on were invisible to
  discovery and got answered from recall once already.
* **Ajani, Nacatl Pariah** -- the rule 2 cautionary tale in CLAUDE.md, in the
  fixture so it is executable rather than only written down. White front, red
  back, so a lookup by the front face must still report {R}{W}; derived from
  the mana cost it reads as mono-white and passes a Selesnya legality check it
  should fail.
* **Etali, Primal Conqueror** -- a double-faced card, the one shape where
  Scryfall puts the stats *and the mana cost* on the faces rather than on the
  card. Reading only the top level is how 501 cards ended up in the pool as
  free spells.
* **Smothering Tithe** -- on the official Game Changers list, so a bracket
  count has something real to find.
* **Goreclaw, Terror of Qal Sisma** -- the mono-green commander the synthetic
  deck below is built around.
* **Cultivator Colossus**, **Llanowar Reborn** -- legal mono-green cards to
  swap and add.
* **Rhystic Study** ({U}) and **Swords to Plowshares** ({W}) -- outside a
  mono-green commander's identity, so a refusal has something to refuse.
* **Black Lotus** -- not legal in Commander, which is a different refusal from
  the identity one and must not be conflated with it.
* **Bag End Banquet** -- a colourless artifact at cmc 6.
* **Regal Behemoth**, **Craterhoof Behemoth**, **Terastodon**,
  **Woodfall Primus**, **Vorinclex, Voice of Hunger** -- mono-green creatures
  between cmc 6 and 8. `suggest.candidate_pool` prefilters to legal cards
  inside the identity within +/-2 of the target's cost and of the same primary
  type, so these are what makes a *real* shortlist for Primeval Titan's slot
  rather than an empty list that asserts nothing.
* **Ajani Steadfast Emblem** -- the one thing here that is not a card. It
  shares a first word with the Ajani above, so the camera reader's
  "emblems are not cards" filter has something that can actually rank
  highly when it breaks. See the comment on the row itself.

`PRINTINGS`, further down, is the same idea for the `printings` table: real
rows, chosen for the cases the camera's corner tier has to survive.
"""

